        /// <summary>
        /// <paramref name="count"/> words from <paramref name="words"/>, never the same one twice.
        /// </summary>
        /// <remarks>
        /// Drawing without replacement matters more than it looks: three of the same word reads to
        /// the model as emphasis rather than as an accident, and a repeated seed is one seed.
        /// <para>
        /// Rejection sampling rather than a shuffle because the caller has already clamped the count
        /// to single figures against a list of hundreds, so a collision is rare and a partial
        /// shuffle would copy the whole index array to save nothing.
        /// </para>
        /// </remarks>
        /// <param name="words">The list to draw from.</param>
        /// <param name="count">How many to take. Clamped to what the list can supply.</param>
        /// <param name="random">
        /// Where the draws come from. A parameter rather than a static reached for in here, for the
        /// same reason as <see cref="Saves.Dice.TryRoll"/>: seeding a session, or replaying one,
        /// stays a change at the call site.
        /// </param>
        public static IReadOnlyList<string> Pick(string[] words, int count, Random random)
        {
            ArgumentNullException.ThrowIfNull(words);
            ArgumentNullException.ThrowIfNull(random);

            var wanted = Math.Clamp(count, 1, words.Length);

            var chosen = new List<string>(wanted);
            var taken = new HashSet<int>(wanted);

            while (chosen.Count < wanted)
            {
                var index = random.Next(words.Length);

                if (taken.Add(index))
                {
                    chosen.Add(words[index]);
                }
            }

            return chosen;
        }

