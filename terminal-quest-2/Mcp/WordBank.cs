        /// One word per line into an array. <see cref="StringSplitOptions.TrimEntries"/> also takes
        /// care of the carriage return, so the lists survive a checkout with either line ending.
        /// </summary>
        private static string[] Split(string source) =>
            source.Split('\n', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);
    }
